"""Per-version HL7 v2 definitions (2.1 .. 2.7.1) for HL7Lens.

  gen_vdict.py import <hl7-dictionary/lib dir> tools/vdict.json   snapshot the npm package (MIT, (c) 2015 Fernando Serrano)
  gen_vdict.py cpp tools/vdict.json src/vdict_gen.cpp              compile the snapshot into C++ tables

Snapshot format: {"_source": ..., "versions": {"2.3": {"segments": {"PID": [desc, [[name, type, rep, table], ...]]},
"types": {"CE": [desc, [[name, type, rep, table], ...]]}}}}.  rep: 0 = repeats without limit, 1 = single, n = up to n.
"""
import json, sys

VERSIONS = ['2.1', '2.2', '2.3', '2.3.1', '2.4', '2.5', '2.5.1', '2.6', '2.7', '2.7.1']
SOURCE = 'hl7-dictionary 1.0.1 (npm), MIT License, Copyright (c) 2015 Fernando Serrano'

def load_js(path):
    t = open(path, encoding='utf-8').read()
    return json.loads(t[t.index('{'):t.rindex('}') + 1])

def item(x):
    return [x.get('desc', ''), x.get('datatype', ''), int(x.get('rep', 1)), int(x.get('table', 0) or 0)]

def do_import(lib, out):
    vers = {}
    for v in VERSIONS:
        segs = load_js(f'{lib}/{v}/segments.js'); types = load_js(f'{lib}/{v}/fields.js')
        vers[v] = {'segments': {k: [s.get('desc', ''), [item(f) for f in s.get('fields', [])]] for k, s in sorted(segs.items())},
                   'types': {k: [d.get('desc', ''), [item(f) for f in d.get('subfields', [])]] for k, d in sorted(types.items())}}
    json.dump({'_source': SOURCE, 'versions': vers}, open(out, 'w'), separators=(',', ':'), sort_keys=True)

def cstr(s):
    out = []
    for b in s.encode('utf-8'):
        c = chr(b)
        if c in '\\"': out.append('\\' + c)
        elif 32 <= b < 127 and c != '?': out.append(c)
        else: out.append('\\%03o' % b)          # octal: never swallows the next character, no trigraphs
    return '"' + ''.join(out) + '"'

def do_cpp(src, out):
    d = json.load(open(src)); pool = {}; strs = []
    def sid(s):
        if s not in pool: pool[s] = len(strs); strs.append(s)
        return pool[s]
    sid('')
    fields = []; lines = []
    for v in VERSIONS:
        V = d['versions'][v]
        for kind in ('segments', 'types'):
            rows = []
            for k, (desc, items) in sorted(V[kind].items()):
                rows.append((sid(k), sid(desc), len(fields), len(items)))
                for (n, t, r, tb) in items: fields.append((sid(n), sid(t), r, tb))
            vname = v.replace('.', '_')
            lines.append(f'static const VEntry {kind.upper()}_{vname}[] = {{' + ','.join('{%d,%d,%d,%d}' % r for r in rows) + '};')
    o = ['// generated by tools/gen_vdict.py from tools/vdict.json - do not edit', '#include "vdict.h"', 'namespace hl7v {',
         'const char* const VSOURCE = ' + cstr(d['_source']) + ';',
         'static const char* const S[] = {' + ','.join(cstr(s) for s in strs) + '};',
         'static const VItem ITEMS[] = {' + ','.join('{%d,%d,%d,%d}' % f for f in fields) + '};']
    o += lines
    o.append('static const VVersion VERS[] = {' + ','.join('{"%s",SEGMENTS_%s,%d,TYPES_%s,%d}' % (v, v.replace('.', '_'), len(d['versions'][v]['segments']), v.replace('.', '_'), len(d['versions'][v]['types'])) for v in VERSIONS) + '};')
    o.append('const VVersion* versions() { return VERS; } int nVersions() { return %d; } const char* str(int i) { return S[i]; } const VItem* items() { return ITEMS; }' % len(VERSIONS))
    o.append('}')
    open(out, 'w').write('\n'.join(o) + '\n')
    print(f'{len(VERSIONS)} versions, {len(fields)} items, {len(strs)} strings')

if __name__ == '__main__':
    {'import': do_import, 'cpp': do_cpp}[sys.argv[1]](sys.argv[2], sys.argv[3])
