"""Generate src/assets_gen.cpp: the HL7 v2 user-defined language (recolored to read on light and dark themes)
and the built-in sample messages.  Usage: gen_assets.py <HL7_v2.xml> <sample.hl7> src/assets_gen.cpp"""
import re, sys
udl, sample, out = sys.argv[1:4]
x = open(udl, encoding='utf-8').read()
x = re.sub(r'<!--.*?-->\s*', '', x, flags=re.S)                     # drop the generator comment (no third-party branding)
x = x.replace('<NotepadPlus>', '<!-- HL7 v2 user language installed by HL7Lens -->\n<NotepadPlus>', 1)
PAL = {  # style -> (fg RRGGBB, bold)  mid-tones that read on both light and dark backgrounds
    'KEYWORDS1': ('1C8C96', 1), 'KEYWORDS2': ('B07D10', 0), 'OPERATORS': ('D2503C', 1), 'NUMBERS': ('C0602A', 0),
    'DELIMITERS1': ('A6489A', 0), 'COMMENTS': ('7A8A9A', 0), 'LINE COMMENTS': ('7A8A9A', 0)}
def restyle(m):
    tag = m.group(0); name = re.search(r'name="([^"]+)"', tag).group(1)
    tag = re.sub(r'\s*colorStyle="\d"', '', tag)
    if name in PAL:
        fg, bold = PAL[name]
        tag = re.sub(r'fgColor="[0-9A-Fa-f]{6}"', 'fgColor="%s"' % fg, tag)
        tag = re.sub(r'fontStyle="\d+"', 'fontStyle="%d"' % bold, tag)
        return tag.replace('<WordsStyle ', '<WordsStyle colorStyle="1" ', 1)
    return tag.replace('<WordsStyle ', '<WordsStyle colorStyle="0" ', 1)
x, n = re.subn(r'<WordsStyle [^>]*/>', restyle, x)
assert n >= 20, n
assert '<!--' in x and x.count('<!--') == 1, 'unexpected comments left in the UDL'
def cs(s):
    o = []
    for line in s.split('\n'):
        o.append('"' + line.replace('\\', '\\\\').replace('"', '\\"').replace('\r', '\\r') + '\\n"')
    return '\n'.join(o)
smp = open(sample, encoding='utf-8').read()
src = ['// GENERATED by tools/gen_assets.py - do not edit', '#include "assets.h"', 'namespace assets {',
       'const char* const UDL_XML =\n' + cs(x) + ';',
       'const char* const SAMPLE =\n' + '\n'.join('"' + l.replace('\\', '\\\\').replace('"', '\\"') + '\\r"' for l in smp.replace('\r\n', '\n').replace('\r', '\n').split('\n') if l) + ';',
       '}']
open(out, 'w', encoding='utf-8').write('\n'.join(src) + '\n')
print('wrote', out, 'styles', n, 'udl bytes', len(x))
