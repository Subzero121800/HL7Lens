"""Generate src/dict_gen.cpp from an HL7 dictionary JSON (segments, datatypes, tables, codesys, msgtypes, fieldTypes, tsFields).
Usage: gen_dict.py dictionary.json src/dict_gen.cpp"""
import json, sys
src, out = sys.argv[1], sys.argv[2]
d = json.load(open(src, encoding="utf-8"))
def cs(s):
    if s is None: return "nullptr"
    s = str(s)
    o = '"'
    for ch in s:
        c = ord(ch)
        if ch == '"': o += '\\"'
        elif ch == '\\': o += '\\\\'
        elif c < 32: o += '\\x%02x' % c
        elif c > 126: o += ''.join('\\x%02x' % b for b in ch.encode('utf-8')) + '""'  # end the hex escape
        else: o += ch
    return o + '"'
L = ['// GENERATED by tools/gen_dict.py from %s (%s) - do not edit' % (src.split('/')[-1], d.get('_built', '')), '#include "dict.h"', 'namespace hl7dict {']
# segments
segs = sorted(d['segments'].items())
for sid, s in segs:
    L.append('static const FieldDef F_%s[] = { %s };' % (sid, ', '.join('{%s, %s, \'%s\'}' % (cs(f['name']), cs(f.get('type', 'ST')), (f.get('flag') or ' ')[0]) for f in s['fields']) or '{nullptr,nullptr,\' \'}'))
    n23 = s.get('n23') or {}
    if n23:
        L.append('static const int N23P_%s[] = { %s };' % (sid, ', '.join(str(int(k)) for k in n23)))
        L.append('static const char* const N23N_%s[] = { %s };' % (sid, ', '.join(cs(v) for v in n23.values())))
L.append('const SegDef SEGMENTS[] = {')
for sid, s in segs:
    n23 = s.get('n23') or {}
    L.append('  {%s, %s, F_%s, %d, %d, %s, %s, %s, %s, %d},' % (cs(sid), cs(s.get('desc', '')), sid, len(s['fields']), int(s.get('max23') or 0), cs(s.get('only')), 'true' if s.get('partial') else 'false', ('N23P_' + sid) if n23 else 'nullptr', ('N23N_' + sid) if n23 else 'nullptr', len(n23)))
L.append('};'); L.append('const int N_SEGMENTS = %d;' % len(segs))
# datatypes
types = sorted(d['datatypes'].items())
for tid, t in types:
    L.append('static const CompDef C_%s[] = { %s };' % (tid, ', '.join('{%s, %s}' % (cs(c['name']), cs(c.get('type', 'ST'))) for c in t['components']) or '{nullptr,nullptr}'))
    v23 = t.get('v23')
    if isinstance(v23, list):
        L.append('static const CompDef C23_%s[] = { %s };' % (tid, ', '.join('{%s, %s}' % (cs(c['name']), cs(c.get('type', 'ST'))) for c in v23)))
L.append('const TypeDef DATATYPES[] = {')
for tid, t in types:
    v23 = t.get('v23')
    if isinstance(v23, list): L.append('  {%s, C_%s, %d, %d, C23_%s, %d},' % (cs(tid), tid, len(t['components']), len(v23), tid, len(v23)))
    else: L.append('  {%s, C_%s, %d, %d, nullptr, 0},' % (cs(tid), tid, len(t['components']), int(v23 or 0)))
L.append('};'); L.append('const int N_DATATYPES = %d;' % len(types))
# tables
tabs = sorted(d['tables'].items())
for i, (k, t) in enumerate(tabs):
    L.append('static const KV T_%d[] = { %s };' % (i, ', '.join('{%s, %s}' % (cs(c), cs(v)) for c, v in t.items())))
L.append('const TableDef TABLES[] = {')
for i, (k, t) in enumerate(tabs): L.append('  {%s, T_%d, %d},' % (cs(k), i, len(t)))
L.append('};'); L.append('const int N_TABLES = %d;' % len(tabs))
def kvlist(name, m):
    L.append('const KV %s[] = { %s };' % (name, ', '.join('{%s, %s}' % (cs(k), cs(v)) for k, v in sorted(m.items()))))
    L.append('const int N_%s = %d;' % (name, len(m)))
kvlist('CODESYS', d['codesys']); kvlist('MSGTYPES', d['msgtypes']); kvlist('FIELDTYPES', d['fieldTypes'])
L.append('const char* const TSFIELDS[] = { %s };' % ', '.join(cs(x) for x in d['tsFields']))
L.append('const int N_TSFIELDS = %d;' % len(d['tsFields']))
L.append('const char* const SOURCE = %s;' % cs(d.get('_source', '')))
L.append('}')
open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('wrote', out, 'segments', len(segs), 'datatypes', len(types), 'tables', len(tabs), 'fieldTypes', len(d['fieldTypes']), 'msgtypes', len(d['msgtypes']))
